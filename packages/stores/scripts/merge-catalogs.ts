// Builds the shipped demo/catalog.json: the hand-kept base rows, then the
// Instacart import (demo/catalog.instacart.json), then the model-seeded
// rows (demo/catalog.seeded.json); the first to claim a normalised name
// wins, every row is tagged with its origin, the reconcile pass runs on
// the result, and derivable fields (department, the generating category)
// are dropped to keep the file small. No model.
//
//   npm run merge:catalog -w @grosher/stores

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Category, Stop } from "@grosher/core";
import { catalogKey, reconcile, type CatalogRow } from "../src/reconcile.ts";

const demo = join(import.meta.dirname, "..", "demo");
const read = <T,>(f: string): T | null => (existsSync(join(demo, f)) ? (JSON.parse(readFileSync(join(demo, f), "utf8")) as T) : null);

const categories = read<Category[]>("categories.json")!;
const base = read<Stop[]>("catalog.base.json")!;
const instacart = read<{ importedAt: string; items: CatalogRow[] }>("catalog.instacart.json");
const seeded = read<{ generatedAt: string | null; model: string | null; items: CatalogRow[] }>("catalog.seeded.json");

const out: CatalogRow[] = base.map((s) => ({ ...s }));
const seen = new Set(out.map((s) => catalogKey(s.name)));
const counts = { base: base.length, instacart: 0, seeded: 0, seededCovered: 0 };
for (const s of instacart?.items ?? []) {
  const k = catalogKey(s.name);
  if (seen.has(k)) continue;
  seen.add(k);
  out.push({ ...s, origin: "instacart" });
  counts.instacart++;
}
for (const s of seeded?.items ?? []) {
  if (!s.category) continue; // the seed file carries the base rows too
  const k = catalogKey(s.name);
  if (seen.has(k)) {
    counts.seededCovered++;
    continue;
  }
  seen.add(k);
  out.push({ ...s, origin: "seeded" });
  counts.seeded++;
}
const r = reconcile(out, categories);
// derivable fields go; `category` stays only as what reconcile needs to tell a seeded row from a base row, so origin carries that now
const items = out.map(({ department: _d, category: _c, ...rest }) => rest);
const header = {
  sources: [
    ...(instacart ? [{ origin: "instacart", name: "The Instacart Online Grocery Shopping Dataset 2017", terms: "non-commercial, with attribution (data/instacart/README.md)", importedAt: instacart.importedAt, items: counts.instacart }] : []),
    ...(seeded ? [{ origin: "seeded", name: `generated by ${seeded.model}`, generatedAt: seeded.generatedAt, items: counts.seeded }] : []),
    { origin: "base", name: "hand-kept rows (scripts/gen-demo.ts)", items: counts.base },
  ],
  mergedAt: new Date().toISOString().slice(0, 10),
  items,
};
writeFileSync(join(demo, "catalog.json"), JSON.stringify(header) + "\n");
console.log(`catalog.json: ${items.length} items = ${counts.base} base + ${counts.instacart} instacart + ${counts.seeded} seeded (${counts.seededCovered} seeded names already covered) · reconcile: ${r.relocated} relocated, ${r.locationsDropped} locations dropped, ${r.aliasesDropped} aliases dropped · ${(JSON.stringify(header).length / 1e6).toFixed(1)} MB`);
