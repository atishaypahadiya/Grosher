// Cook mode's ingredients: how each is measured once bought and how the store sells it (packages/core meals/plan.ts
// does the arithmetic). The names are written as a shopper writes a list line and resolve to Grosher's shelves
// ("Toor dal 500 g" → A4, "Onions × 6" → produce). Pack sizes are the common ones on a big grocery's shelf.
//
// pantry: salt, sugar, oil and the everyday dried spices: shown under "You probably have", unticked.

import type { IngredientInfo, MealCategory } from "@grosher/core";

/** by the piece, `eachG` grams each: "Onions × 6" */
const pc = (key: string, name: string, category: MealCategory, eachG: number, extra: Partial<IngredientInfo> = {}): IngredientInfo => ({ key, name, category, base: "count", eachG, buy: { kind: "count" }, ...extra });
/** in packs (grams or millilitres): "Toor dal 500 g" */
const pk = (key: string, name: string, category: MealCategory, base: "g" | "ml", sizes: number[], extra: Partial<IngredientInfo> = {}): IngredientInfo => ({ key, name, category, base, buy: { kind: "pack", sizes }, ...extra });
/** loose by weight, in steps: "Ginger 100 g" */
const lo = (key: string, name: string, category: MealCategory, step: number, extra: Partial<IngredientInfo> = {}): IngredientInfo => ({ key, name, category, base: "g", buy: { kind: "loose", step }, ...extra });
/** by the bunch, `bunchG` grams a bunch: "Cilantro × 1 bunch" */
const herb = (key: string, name: string, bunchG: number, extra: Partial<IngredientInfo> = {}): IngredientInfo => ({ key, name, category: "herbs", base: "count", bunchG, buy: { kind: "count" }, ...extra });
/** a pantry spice, 100 g packs */
const spice = (key: string, name: string, aliases: string[] = [], extra: Partial<IngredientInfo> = {}): IngredientInfo => pk(key, name, "spices", "g", [100], { pantry: true, aliases, ...extra });
/** a spice blend or masala most kitchens do not keep (bought) */
const blend = (key: string, name: string, sizes: number[], aliases: string[] = []): IngredientInfo => pk(key, name, "spices", "g", sizes, { aliases });

